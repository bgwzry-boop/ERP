import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { chromium, expect } from "@playwright/test";
import { createApiServer } from "../server/apiServer.mjs";
import { withLocalRepositoryFixture } from "./helpers/localRepositoryFixture.mjs";
import { listenTestServer, getTestServerBaseUrl, closeTestServer, requestJson } from "./helpers/apiIntegrationTestHarness.mjs";
const storage = await mkdtemp(join(tmpdir(), "erp-entry-split-"));
const output = resolve(".erp-local-storage/order-entry-split-20261025");
await mkdir(output, { recursive: true });
let server, browser;
try {
  server = createApiServer(withLocalRepositoryFixture({runtimeMode:"test", runtimeStorageRoot:storage, seedSource:"synthetic", allowLocalFixture:true, applyProductionEnvFile:false, authMode:"prototype", authSecret:randomBytes(32).toString("hex"), fixedPreviewUserId:"U-MANAGER-A", allowLegacyIdentityHeaders:false, allowDefaultSeedUser:false}));
  await server.ready; await listenTestServer(server);
  const origin = getTestServerBaseUrl(server);
  const login = (await requestJson(origin, "/api/auth/prototype-login", {method:"POST", headers:{"content-type":"application/json"}, body:JSON.stringify({userId:"U-MANAGER-A"}), expectedStatus:200})).body;
  const api = async path => (await requestJson(origin, `/api${path}`, {headers:{authorization:`Bearer ${login.session.accessToken}`},expectedStatus:200})).body;
  browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:980}});
  const errors=[], writes=[], previews=[]; let quote, confirmation, lastRecognizedDraft;
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/api/**", async route => {
    const req=route.request(), url=new URL(req.url()), headers={...req.headers()}; delete headers.host; delete headers.origin;
    const result=await fetch(origin+url.pathname+url.search,{method:req.method(),headers,body:["GET","HEAD"].includes(req.method())?undefined:req.postDataBuffer()});
    const body=Buffer.from(await result.arrayBuffer());
    if (req.method() === "POST" && url.pathname.endsWith("/order-drafts/recognize") && result.ok) lastRecognizedDraft = JSON.parse(body).draft;
    if(req.method()==="POST" && url.pathname.endsWith("/price-quote") && result.ok)quote=JSON.parse(body).quote;
    if(req.method()==="POST" && url.pathname.endsWith("/split-preview") && result.ok)previews.push(JSON.parse(body).splitPlan);
    if(req.method()==="POST" && url.pathname.endsWith("/split-confirm")) {
      writes.push({key:headers["idempotency-key"],body:req.postData()});
      if(result.ok)confirmation=JSON.parse(body);
      if(writes.length<=2){ await route.fulfill({status:writes.length===1?500:409,contentType:"application/json",body:JSON.stringify({code:"ISOLATED_RECEIPT_LOSS",message:"isolated receipt boundary"})}); return; }
    }
    await route.fulfill({status:result.status,contentType:result.headers.get("content-type")||"application/json",body});
  });
  await page.goto("http://127.0.0.1:4174/?entrySplit=isolated&erpViewport=desktop#order-entry");
  const source = page.getByLabel("客户订单原文");
  const newOrder = page.getByRole("button", { name: /新建订单$/u });
  await expect(source).toBeVisible();
  await expect(source).toHaveValue(/张三服饰/, { timeout: 15000 });
  const message = "王五包装 30*38*10 红色 40个 2099-11-02自提";
  await source.fill(message);
  await expect(source).toHaveValue(message);
  await page.getByRole("button",{name:"识别客户消息",exact:true}).click();
  await expect(page.getByLabel("第1行数量",{exact:true})).toHaveValue("40");
  // 2026-11-05 紧凑版：交付、需要日期（本行）、改价、拆行收在每行的「更多」里。
  const openRow = async n => { const more=page.getByRole("button",{name:`第${n}行更多`,exact:true}); if (await more.count()) await more.click(); };
  await openRow(1);
  await page.getByLabel("第1行需要日期",{exact:true}).fill("2099-11-02");
  const previewButton = page.getByRole("button",{name:"按客户/交付拆单",exact:true});
  await previewButton.click();
  let dialog=page.getByRole("dialog",{name:"拆单预览与确认"});
  await expect(dialog).toContainText("当前只有一个交付组");
  await expect(newOrder).toBeDisabled();
  await expect(dialog.getByRole("button",{name:"确认生成 1 张订单",exact:true})).toBeDisabled();
  await page.keyboard.press("Escape"); await expect(dialog).toHaveCount(0); await expect(previewButton).toBeFocused();
  await page.getByLabel("本行使用授权本单价",{exact:true}).check();
  await page.getByLabel("第1行其他费（元）",{exact:true}).fill("9");
  await page.getByLabel("改价原因",{exact:true}).fill("isolated one-time charge before row split");
  // 2026-11-08：报价不再是单独一步；拆单预览前自动按价格表算价（不下单）。
  await previewButton.click(); dialog=page.getByRole("dialog",{name:"拆单预览与确认"});
  await expect(dialog).toBeVisible(); await page.keyboard.press("Escape"); await expect(dialog).toHaveCount(0);
  const firstQuote = quote.quoteId;
  assert.equal(quote.lines[0].otherFee,9);
  await page.getByRole("button",{name:"拆分第1行明细",exact:true}).click();
  await expect(page.getByLabel("第1行数量",{exact:true})).toHaveValue("20");
  await expect(page.getByLabel("第2行数量",{exact:true})).toHaveValue("20");
  await openRow(1); await openRow(2);
  await expect(page.getByLabel("本行使用授权本单价",{exact:true}).nth(0)).not.toBeChecked();
  await expect(page.getByLabel("本行使用授权本单价",{exact:true}).nth(1)).not.toBeChecked();
  await page.getByLabel("第2行交付方式",{exact:true}).selectOption("送货");
  await page.getByLabel("第2行需要日期",{exact:true}).fill("2099-11-03");
  await previewButton.click(); dialog=page.getByRole("dialog",{name:"拆单预览与确认"});
  await expect(dialog).toBeVisible();
  assert.notEqual(quote.quoteId,firstQuote,"row splitting invalidates the original quote");
  assert.equal(quote.lines.reduce((sum,line)=>sum+line.otherFee,0),0,"one-time fees are not cloned into split lines");
  await expect(dialog.getByRole("button",{name:"确认生成 2 张订单",exact:true})).toBeEnabled();
  assert.equal(writes.length,0,"preview does not create orders");
  await page.screenshot({path:join(output,"desktop-split-review.png"),fullPage:true});
  await page.setViewportSize({width:900,height:900});
  assert.equal(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth),true,"compact desktop dialog must not overflow");
  await page.screenshot({path:join(output,"compact-split-review.png"),fullPage:true});
  await dialog.getByRole("button",{name:"返回修改",exact:true}).click();
  await expect(previewButton).toBeFocused(); assert.equal(writes.length,0,"return sends no order mutation");
  const oldHash=previews.at(-1).planHash;
  await page.getByLabel("第2行需要日期",{exact:true}).fill("2099-11-04");
  await previewButton.click(); dialog=page.getByRole("dialog",{name:"拆单预览与确认"});
  await expect(dialog).toBeVisible();
  assert.notEqual(previews.at(-1).planHash,oldHash,"edited delivery date requires a new server plan");
  await dialog.getByRole("button",{name:"确认生成 2 张订单",exact:true}).click();
  const retry=dialog.getByRole("button",{name:"按原内容重试拆单",exact:true});
  await expect(retry).toBeEnabled();
  await expect(newOrder).toBeDisabled();
  await expect(dialog.getByRole("button",{name:"返回修改",exact:true})).toBeDisabled();
  await page.keyboard.press("Escape"); await expect(dialog).toBeVisible();
  await retry.click(); await expect(retry).toBeEnabled();
  await retry.click(); await expect(dialog).toHaveCount(0);
  await expect(page.locator(".pricing-actions [role=status]")).toContainText("已生成 2 张正式订单");
  assert.equal(writes.length,3); assert.equal(new Set(writes.map(x=>x.key)).size,1); assert.equal(new Set(writes.map(x=>x.body)).size,1);
  const payload=JSON.parse(writes[0].body);
  assert.equal(payload.pricingQuoteId,quote.quoteId); assert.equal(payload.splitPlanHash,previews.at(-1).planHash);
  assert.deepEqual(payload.confirmedAffectedOrderLineIds,[]);
  const pool=await api("/order-lines?customerId=C003&pageSize=100");
  const created=pool.items.filter(line=>confirmation.orderIds.includes(line.orderNo));
  assert.equal(created.length,2); assert.equal(new Set(created.map(x=>x.orderNo)).size,2);
  assert.equal(created.reduce((sum,x)=>sum+Number(x.qty),0),40);
  assert.equal(confirmation.priceSnapshots.reduce((sum,x)=>sum+x.amount,0),quote.lines.reduce((sum,x)=>sum+x.amount,0));
  assert.deepEqual(errors,[]);
  await page.setViewportSize({width:1440,height:980});
  await page.screenshot({path:join(output,"desktop-split-success.png"),fullPage:true});
  const openPool = page.getByRole("button", { name: "查看订单跟踪", exact: true });
  await expect(openPool).toBeEnabled();
  await openPool.click();
  await expect(page).toHaveURL(/#order-pool$/u);
  await newOrder.click();
  await expect(source).toHaveValue("");
  const quantity = page.getByLabel("第1行数量", { exact: true });
  await expect(quantity).toHaveCount(0);
  await expect(page.getByText("尚未建立草稿", { exact: true })).toBeVisible();
  await source.fill("王五包装 30*38*10 红色 10个 明天自提");
  await page.getByRole("button", { name: "识别客户消息", exact: true }).click();
  await expect(quantity).toHaveValue("10");
  const previousDraft = lastRecognizedDraft;
  const discard = page.getByRole("alertdialog", { name: "放弃当前修改？", exact: true });
  await quantity.fill("11");
  await newOrder.click();
  await expect(discard).toBeVisible();
  await discard.getByRole("button", { name: "继续编辑", exact: true }).click();
  await expect(discard).toHaveCount(0);
  await expect(quantity).toHaveValue("11");
  await expect(source).toHaveValue(/10个/u);
  await newOrder.click();
  await discard.getByRole("button", { name: "放弃并新建", exact: true }).click();
  await expect(source).toHaveValue("");
  await expect(quantity).toHaveCount(0);
  const previousDraftRead = await api(`/order-drafts?draftId=${encodeURIComponent(previousDraft.draftId)}`);
  assert.equal(previousDraftRead.items[0].sourceText, previousDraft.sourceText);
  assert.equal(previousDraftRead.items[0].clientRevision, previousDraft.clientRevision);

  await source.fill("合成未识别原文");
  await newOrder.click();
  await expect(discard).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(discard).toHaveCount(0);
  await expect(source).toHaveValue("合成未识别原文");

  await source.fill("王五包装 30*38*10 红色 12个 明天自提");
  await page.getByRole("button", { name: "识别客户消息", exact: true }).click();
  await expect(quantity).toHaveValue("12");
  await quantity.fill("13");
  await page.getByRole("button", { name: "保存草稿", exact: true }).click();
  await expect(page.getByText("草稿已保存。核对无误后点「开单」或「确认下单」。", { exact: true })).toBeVisible();
  await newOrder.click();
  await expect(source).toHaveValue("");
  await expect(quantity).toHaveCount(0);
  await expect(discard).toHaveCount(0);
  assert.deepEqual(errors, []);
  await page.screenshot({path:join(output,"desktop-next-order.png"),fullPage:true});
  await writeFile(join(output,"validation.json"),JSON.stringify({status:"passed",isolated:true,createdOrderCount:2,quantity:40,quotePreserved:true,retryRequests:3,uniqueRequestCount:1,previewCancellationWrites:0,postSuccessPool:true,newOrderBlank:true,unsavedChangesGuard:true,oldDraftPreserved:true,savedDraftStartsBlank:true,pageErrors:errors,viewports:[1440,900]},null,2));
  console.log("Order entry split desktop passed: quantity and quote conservation, server grouping, exact retry, post-success order-pool access, and new-order guards for unsaved rows, unrecognized text, saved drafts and split preview.");
} finally {
  await browser?.close(); if(server)await closeTestServer(server); await rm(storage,{recursive:true,force:true});
}
