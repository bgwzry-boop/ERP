export function resolveCheckGroupFrom(groups, groupName, ancestry = []) {
  const entries = groups[groupName];
  if (!entries) {
    throw new Error(`Unknown check group: ${groupName}`);
  }
  if (ancestry.includes(groupName)) {
    throw new Error(`Cyclic check group reference: ${[...ancestry, groupName].join(" -> ")}`);
  }

  return entries.flatMap((entry) => (
    entry.startsWith("@")
      ? resolveCheckGroupFrom(groups, entry.slice(1), [...ancestry, groupName])
      : entry
  ));
}

export function resolveCheckGroup(groupName) {
  return resolveCheckGroupFrom(CHECK_GROUPS, groupName);
}

export function listCheckGroups() {
  return Object.keys(CHECK_GROUPS);
}
